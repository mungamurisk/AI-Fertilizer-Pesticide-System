
package fertilizer_pesticide_system.service;

import fertilizer_pesticide_system.dto.RecommendationRequest;
import fertilizer_pesticide_system.dto.RecommendationResponse;
import fertilizer_pesticide_system.dto.MlPredictionRequest;
import fertilizer_pesticide_system.dto.MlPredictionResponse;
import org.springframework.stereotype.Service;

@Service
public class RecommendationService {

    private final MlPredictionService mlPredictionService;

    public RecommendationService(MlPredictionService mlPredictionService) {
        this.mlPredictionService = mlPredictionService;
    }

    public RecommendationResponse getRecommendation(
            RecommendationRequest request) {

        MlPredictionRequest mlRequest = new MlPredictionRequest();
        mlRequest.setTemperature(request.getTemperature());
        mlRequest.setHumidity(request.getHumidity());
        mlRequest.setMoisture(request.getMoisture());
        mlRequest.setSoilType(request.getSoilType());
        mlRequest.setCropType(request.getCropType());
        mlRequest.setNitrogen(request.getNitrogen());
        mlRequest.setPotassium(request.getPotassium());
        mlRequest.setPhosphorus(request.getPhosphorus());

        MlPredictionResponse prediction =
                mlPredictionService.predict(mlRequest);

        return new RecommendationResponse(
                prediction.getFertilizer(),
                "Recommendation generated by the trained Python ML model.");
    }
}
