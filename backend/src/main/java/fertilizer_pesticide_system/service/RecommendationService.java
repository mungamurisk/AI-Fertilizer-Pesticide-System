
package fertilizer_pesticide_system.service;

import fertilizer_pesticide_system.dto.RecommendationRequest;
import fertilizer_pesticide_system.dto.RecommendationResponse;
import org.springframework.http.HttpEntity;
import org.springframework.http.HttpHeaders;
import org.springframework.http.MediaType;
import org.springframework.http.ResponseEntity;
import org.springframework.stereotype.Service;
import org.springframework.web.client.RestClientException;
import org.springframework.web.client.RestTemplate;

import java.util.HashMap;
import java.util.Map;

@Service
public class RecommendationService {

    private final RestTemplate restTemplate = new RestTemplate();

    public RecommendationResponse getRecommendation(
            RecommendationRequest request) {

        String pythonUrl = "http://127.0.0.1:5000/predict";

        Map<String, Object> input = new HashMap<>();
        input.put("temperature", request.getTemperature());
        input.put("humidity", request.getHumidity());
        input.put("moisture", request.getMoisture());
        input.put("soilType", request.getSoilType());
        input.put("cropType", request.getCropType());
        input.put("nitrogen", request.getNitrogen());
        input.put("potassium", request.getPotassium());
        input.put("phosphorus", request.getPhosphorus());

        HttpHeaders headers = new HttpHeaders();
        headers.setContentType(MediaType.APPLICATION_JSON);

        HttpEntity<Map<String, Object>> entity =
                new HttpEntity<>(input, headers);

        try {
            ResponseEntity<Map> response =
                    restTemplate.postForEntity(
                            pythonUrl, entity, Map.class);

            Map<?, ?> result = response.getBody();

            if (result == null || result.get("fertilizer") == null) {
                throw new IllegalStateException(
                        "Python API returned no fertilizer prediction.");
            }

            String fertilizer =
                    result.get("fertilizer").toString();

            String reason =
                    "Recommendation generated by the trained Python ML model.";

            return new RecommendationResponse(fertilizer, reason);

        } catch (RestClientException e) {
            throw new IllegalStateException(
                    "Could not connect to Python ML API at "
                            + pythonUrl, e);
        }
    }
}
